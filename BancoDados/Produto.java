
import java.sql.Date;

public class Produto {
    private String nome;
    private double valor;
    private int qtde;
    private Date data;
    
    public String getNome() {
        return nome;
    }
    public double getValor() {
        return valor;
    }
    public int getQtde() {
        return qtde;
    }
    public Date getData() {
        return data;
    }

    
}
